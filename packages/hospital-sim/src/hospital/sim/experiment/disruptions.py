"""Exogenous disruption injectors (doc 04 §3.13 / §4.4 / nuance 4.10).

Division of ownership: ``data`` owns the *schedule* (``DisruptionEvent``: when,
how big, what target), ``sim`` owns the *mechanism*. Every injector fires at
the ``DISRUPTION`` tier, so at one instant it lands *after* any same-instant
decision — a plan cannot pre-dodge a disruption it could not have known about
(the anti-clairvoyance guarantee). Effects derive purely from the spec plus
deterministic target resolution, so BASELINE and OPTIMIZED face the identical
weather.

Mechanisms:

* ``surge`` — the *arrivals* are generated by ``data.workload.generate_workload``
  (the one workload generator, on its own ``surge``-keyed substreams — additive,
  never a perturbation of the base week); the injector only emits the
  ``DisruptionInjected`` marker at the surge instant.
* ``staff_absence`` — marks the staff absent in ``World`` and ``Interrupt``s the
  agent; the staff process re-queues unfinished work and sleeps out the window.
* ``zone_closure`` — opens a ``World`` zone-closure window: FREE bays close
  immediately, occupied bays are never yanked from under a patient, and a bay
  freed mid-window parks CLOSED (the closure governs late-freed capacity for
  the whole window); or, with a ``node:<id>`` / ``edge:<a>:<b>`` target, masks
  the route graph so live rerouting through ``World.route`` kicks in — actors
  needing a severed destination wait for the reopening (``World.await_route``),
  never crash. All closures are refcounted, so overlapping windows on the same
  target never reopen each other early; fully undone when the LAST window ends.
* ``imaging_outage`` — seizes the suite's full capacity with maximum-urgency
  requests for the window (an in-progress scan finishes first — the outage
  takes effect when the machine frees, and holds only the REMAINDER of the
  declared window), then releases exactly what it took. Only an omitted target
  selects the default suite; an unknown explicit target is recorded as
  unresolved and perturbs nothing.

Every injector restores exactly what it perturbed — a partial restore would be
a permanent, arm-varying bias (nuance 4.10).
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from hospital.core import (
    DisruptionInjected,
    Duration,
    EventLog,
    NodeId,
    RandomStreams,
    SimTime,
    StaffId,
    StaffRole,
    ZoneId,
)
from hospital.sim.physics.executor import PriorityTier, TaskExecutor

if TYPE_CHECKING:
    from collections.abc import Callable, Generator, Mapping

    import simpy

    from hospital.data.scenario import DisruptionEvent
    from hospital.sim.physics.world import World

# Outranks every patient priority (>= -5): the outage always heads the queue.
_OUTAGE_PRIORITY = -1_000_000


def schedule_disruptions(
    env: simpy.Environment,
    world: World,
    executor: TaskExecutor,
    streams: RandomStreams,
    events: tuple[DisruptionEvent, ...],
    *,
    staff_processes: Mapping[StaffId, simpy.Process],
    event_log: EventLog,
) -> None:
    """Wire one injector process per scheduled event (composition root only).

    ``streams`` is threaded for future magnitude sampling on the isolated
    ``substream("disruption", ...)`` domain; the v1 injectors are fully
    determined by their spec and draw nothing.
    """
    for ev in events:
        if ev.kind == "surge":
            env.process(_surge(executor, event_log, ev))
        elif ev.kind == "staff_absence":
            env.process(_absence(world, executor, event_log, ev, staff_processes))
        elif ev.kind == "zone_closure":
            env.process(_closure(world, executor, event_log, ev))
        else:
            env.process(_imaging_outage(world, executor, event_log, ev))


def _until(ev: DisruptionEvent) -> SimTime:
    return ev.at + ev.duration


def _delay_to(executor: TaskExecutor, at: SimTime) -> simpy.Event:
    dt = at.root - int(executor.env.now)
    return executor.delay(Duration(max(dt, 0)), PriorityTier.DISRUPTION)


def _surge(
    executor: TaskExecutor, event_log: EventLog, ev: DisruptionEvent
) -> Generator[simpy.Event, object]:
    """The surge *arrivals* already ride the workload; this is the audit marker."""
    yield _delay_to(executor, ev.at)
    event_log.append(
        DisruptionInjected(
            occurred_at=executor.now(),
            disruption="surge",
            detail=f"magnitude={ev.magnitude}",
        )
    )


def _resolve_staff(world: World, target: str | None) -> StaffId | None:
    """Deterministic target resolution: exact id, then role name, then first nurse."""
    roster = sorted(world.roster(), key=lambda m: m.id.root)
    if not roster:
        return None
    if target is not None:
        for m in roster:
            if m.id.root == target:
                return m.id
        role_values = {r.value for r in StaffRole}
        if target in role_values:
            for m in roster:
                if m.role.value == target:
                    return m.id
        return None
    return next((m.id for m in roster if m.role is StaffRole.NURSE), roster[0].id)


def _absence(
    world: World,
    executor: TaskExecutor,
    event_log: EventLog,
    ev: DisruptionEvent,
    staff_processes: Mapping[StaffId, simpy.Process],
) -> Generator[simpy.Event, object]:
    yield _delay_to(executor, ev.at)
    staff = _resolve_staff(world, ev.target)
    detail = staff.root if staff is not None else f"unresolved target {ev.target!r}"
    event_log.append(
        DisruptionInjected(occurred_at=executor.now(), disruption="staff_absence", detail=detail)
    )
    if staff is None:
        return
    world.set_absent(staff, _until(ev))
    proc = staff_processes.get(staff)
    if proc is not None and proc.is_alive:
        proc.interrupt("staff_absence")


def _closure(
    world: World,
    executor: TaskExecutor,
    event_log: EventLog,
    ev: DisruptionEvent,
) -> Generator[simpy.Event, object]:
    yield _delay_to(executor, ev.at)
    target = ev.target
    event_log.append(
        DisruptionInjected(
            occurred_at=executor.now(), disruption="zone_closure", detail=str(target)
        )
    )
    undo: list[Callable[[], None]] = []
    if target is not None and target.startswith("node:"):
        node = NodeId(target.removeprefix("node:"))
        world.close_node(node)
        undo.append(lambda n=node: world.open_node(n))
    elif target is not None and target.startswith("edge:"):
        _, a, b = target.split(":", 2)
        edge = (NodeId(a), NodeId(b))
        world.block_edge(*edge)
        undo.append(lambda e=edge: world.unblock_edge(*e))
    elif target is not None:
        # a zone id: the closure governs the zone for the WHOLE window — FREE
        # bays close now, occupied bays are never yanked, and a bay freed
        # mid-window parks CLOSED until the window ends (World owns that rule,
        # refcounted so overlapping windows never reopen each other early).
        zone = ZoneId(target)
        world.begin_zone_closure(zone)
        undo.append(lambda z=zone: world.end_zone_closure(z))
    yield executor.delay(ev.duration, PriorityTier.DISRUPTION)
    for restore in reversed(undo):
        restore()


def _resolve_imaging(
    imaging: Mapping[NodeId, simpy.PriorityResource], target: str | None
) -> NodeId | None:
    """Deterministic suite resolution: only an OMITTED target selects the default.

    An explicit-but-unknown target resolves to nothing — it is recorded as
    unresolved and capacity is left untouched (mirrors ``_resolve_staff``);
    silently outaging the first suite would perturb physics the scenario never
    asked to perturb.
    """
    nodes = sorted(imaging, key=lambda n: n.root)
    if not nodes:
        return None
    if target is None:
        return nodes[0]
    return next((n for n in nodes if n.root == target), None)


def _imaging_outage(
    world: World,
    executor: TaskExecutor,
    event_log: EventLog,
    ev: DisruptionEvent,
) -> Generator[simpy.Event, object]:
    yield _delay_to(executor, ev.at)
    imaging = world.resources.imaging
    node = _resolve_imaging(imaging, ev.target)
    if node is None:
        detail = "no imaging nodes" if not imaging else f"unresolved target {ev.target!r}"
        event_log.append(
            DisruptionInjected(
                occurred_at=executor.now(), disruption="imaging_outage", detail=detail
            )
        )
        return
    event_log.append(
        DisruptionInjected(
            occurred_at=executor.now(), disruption="imaging_outage", detail=node.root
        )
    )
    resource = imaging[node]
    requests = [resource.request(priority=_OUTAGE_PRIORITY) for _ in range(int(resource.capacity))]
    for request in requests:
        yield request
    # Hold only the REMAINDER of the declared window: an in-progress scan
    # finishes first, so acquisition can land mid-window (or past it) — the
    # outage still ends at ``ev.at + ev.duration``, never at acquisition +
    # duration, which could fall entirely outside the declared window.
    remaining = _until(ev).root - int(executor.env.now)
    if remaining > 0:
        yield executor.delay(Duration(remaining), PriorityTier.DISRUPTION)
    for request in requests:
        resource.release(request)


__all__ = ["schedule_disruptions"]
